#!/usr/bin/env node
// Runs after `astro build` (see package.json "build").
// Adds security/cache headers and 301 redirects from the old Wix URLs to the routes in
// .vercel/output/config.json (Vercel Build Output API v3) written by @astrojs/vercel.
// Done here, not in vercel.json, so they are guaranteed to be part of the deployed routing.
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { recipeCategories } from '../src/data/categories.ts';

const ROOT = path.resolve(import.meta.dirname, '..');
const CONFIG = path.join(ROOT, '.vercel/output/config.json');
if (!existsSync(CONFIG)) {
  console.error('vercel-postbuild: .vercel/output/config.json not found – did astro build run with @astrojs/vercel?');
  process.exit(1);
}

// ---------- redirects (old Wix path → new path)
const redirects = new Map();
const add = (from, to) => redirects.set(from, to);

// Every blog post (generated by the scraper): /post/<slug> → /recipes/<slug> | /blog/<slug>
const posts = JSON.parse(readFileSync(path.join(ROOT, 'src/data/wix-redirects.json'), 'utf8'));
for (const [from, to] of Object.entries(posts)) add(from, to);

// Wix static pages
add('/keto-recipes', '/recipes');
add('/keto-blog', '/blog');
add('/about-happy-keto', '/about');
add('/contact-8', '/contact');
add('/ketochallenge', '/challenge');
add('/payment-request-page', '/challenge');
add('/iherb-מומלצים', '/favorites');
add('/מדיניותפרטיות', '/privacy');
add('/general-8', '/');

// Wix category landing pages and blog-category feeds
for (const c of recipeCategories) {
  add(c.wixPage, `/recipes/category/${c.slug}`);
  for (const w of c.wix) add(`/recipes/categories/${w}`, `/recipes/category/${c.slug}`);
}
for (const w of ['בלוג-קטוגני', 'מדריך-לקיטו', 'המדריך-לתזונה-דלת-פחמימות', 'low-carb-1']) add(`/recipes/categories/${w}`, '/blog');
for (const w of ['מתכונים', 'lunch-box']) add(`/recipes/categories/${w}`, '/recipes');

// English (/en/…) versions of the old Wix pages: to the English page where one exists, else the Hebrew target.
const EN_PAGES = new Set(['/', '/about', '/contact', '/challenge', '/favorites', '/privacy']);
for (const [from, to] of [...redirects]) {
  if (from.startsWith('/post/') || from.startsWith('/recipes/categories/')) continue; // posts: wildcard below
  add('/en' + from, EN_PAGES.has(to) ? (to === '/' ? '/en' : '/en' + to) : to);
}

const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
/** Match both the raw (Hebrew) and the percent-encoded spelling, with or without a trailing slash. */
const pathPattern = (p) => {
  const encoded = p.split('/').map(encodeURIComponent).join('/');
  const forms = [...new Set([p, encoded])].map(escapeRe);
  return `^(?:${forms.join('|')})/?$`;
};

// HTTP header values must be ASCII: percent-encode the target path.
const encodePath = (p) => p.split('/').map(encodeURIComponent).join('/');
const redirectRoutes = [...redirects].map(([from, to]) => ({
  src: pathPattern(from),
  headers: { Location: encodePath(to) },
  status: 301,
}));
// Wildcards: anything else under the old Wix sections.
redirectRoutes.push(
  // The original had no English posts: /en/post/… and /en/recipes… go to the Hebrew pages.
  { src: '^/en/(post|recipes)(/.*)?$', headers: { Location: '/$1$2' }, status: 301 },
  { src: '^/en/(challenge-page)(?:/.*)?$', headers: { Location: '/en/challenge' }, status: 301 },
  { src: '^/post/(.+?)/?$', headers: { Location: '/recipes/$1' }, status: 301 }, // unknown post → try recipes (404 page if missing)
  { src: '^/recipes/categories/?$', headers: { Location: '/recipes' }, status: 301 },
  // Wix tag pages → the catalog filtered by that tag (search matches tags).
  { src: '^/recipes/tags/([^/]+)/?$', headers: { Location: '/recipes?q=$1' }, status: 301 },
  { src: '^/recipes/page/\\d+/?$', headers: { Location: '/recipes' }, status: 301 },
  { src: '^/challenge-page(?:/.*)?$', headers: { Location: '/challenge' }, status: 301 },
  { src: '^/profile(?:/.*)?$', headers: { Location: '/about' }, status: 301 },
  { src: '^/blog-feed\\.xml$', headers: { Location: '/blog' }, status: 301 },  // Anna's admin entry: one easy address on her own domain. 302 so the target can change later.
  { src: '^/admin/?$', headers: { Location: 'https://app.pagescms.org/kuntsmananna/happyketo-site/main' }, status: 302 },
  { src: '^/dashboard-hk7m2q/?$', headers: { Location: '/admin/dashboard' }, status: 301 }, // the dashboard's first address
);

// ---------- headers
// ---------- Content-Security-Policy
// Only same-origin scripts plus the exact inline scripts Astro emitted (by SHA-256), so injected markup in a post
// can never run script. Styles allow 'unsafe-inline' (Astro inlines small stylesheets; components use style="").
const STATIC = path.join(ROOT, '.vercel/output/static');
const htmlFiles = (dir) =>
  readdirSync(dir, { withFileTypes: true }).flatMap((d) =>
    d.isDirectory() ? htmlFiles(path.join(dir, d.name)) : d.name.endsWith('.html') ? [path.join(dir, d.name)] : [],
  );
const scriptHashes = new Set();
for (const file of htmlFiles(STATIC)) {
  for (const [, attrs, body] of readFileSync(file, 'utf8').matchAll(/<script([^>]*)>([\s\S]*?)<\/script>/g)) {
    if (/\bsrc=/.test(attrs) || /application\/ld\+json/.test(attrs) || !body) continue;
    scriptHashes.add(`'sha256-${createHash('sha256').update(body).digest('base64')}'`);
  }
}
if (scriptHashes.size > 40) {
  console.error(`vercel-postbuild: ${scriptHashes.size} distinct inline scripts – a page probably inlines per-page data; check before shipping a huge CSP header.`);
  process.exit(1);
}
const csp = [
  "default-src 'self'",
  `script-src 'self' ${[...scriptHashes].sort().join(' ')}`,
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data:",
  "font-src 'self'",
  "media-src 'self'",
  'frame-src https://www.youtube-nocookie.com',
  "connect-src 'self' https://api.web3forms.com",
  "form-action 'self' https://api.web3forms.com",
  "object-src 'none'",
  "base-uri 'self'",
  "frame-ancestors 'self'",
  'upgrade-insecure-requests',
].join('; ');

const securityHeaders = {
  'Content-Security-Policy': csp,
  'X-Content-Type-Options': 'nosniff',
  'X-Frame-Options': 'SAMEORIGIN',
  'Referrer-Policy': 'strict-origin-when-cross-origin',
  'Permissions-Policy': 'camera=(), microphone=(), geolocation=(), interest-cohort=()',
  'Strict-Transport-Security': 'max-age=63072000; includeSubDomains',
};
const headerRoutes = [
  { src: '^/(.*)$', headers: securityHeaders, continue: true },
  // Videos and favicon change rarely; hashed /_astro/* assets are already immutable (set by the adapter).
  { src: '^/videos/(.*)$', headers: { 'Cache-Control': 'public, max-age=2592000, stale-while-revalidate=86400' }, continue: true },
  { src: '^/(favicon\\.svg|og-default\\.jpg|robots\\.txt)$', headers: { 'Cache-Control': 'public, max-age=86400' }, continue: true },
];

// ---------- patch config.json: headers first, redirects before the filesystem handle
const config = JSON.parse(readFileSync(CONFIG, 'utf8'));
const routes = config.routes ?? [];
if (routes.some((r) => r.src === '^/post/(.+?)/?$')) {
  console.log('vercel-postbuild: already applied');
  process.exit(0);
}
const fsIndex = routes.findIndex((r) => r.handle === 'filesystem');
if (fsIndex < 0) {
  // Redirects appended after the filesystem handle would never match – fail the build instead of shipping that.
  console.error('vercel-postbuild: no "filesystem" handle in config.json routes – the adapter output format changed.');
  process.exit(1);
}
const insertAt = fsIndex;
// Missing /en/* addresses get the English 404 page (the adapter's catch-all serves the Hebrew one).
const after = routes.slice(insertAt);
const catchAll = after.findIndex((r) => r.src === '^/.*$' && r.status === 404);
if (catchAll >= 0) after.splice(catchAll, 0, { src: '^/en(?:/.*)?$', dest: '/en/404/index.html', status: 404 });
config.routes = [...headerRoutes, ...routes.slice(0, insertAt), ...redirectRoutes, ...after];
writeFileSync(CONFIG, JSON.stringify(config, null, 2));
console.log(`vercel-postbuild: added ${headerRoutes.length} header routes (CSP with ${scriptHashes.size} script hashes) and ${redirectRoutes.length} redirects`);
